const express = require("express");
const router = express.Router();
const { protect, allowRoles } = require("../middlewares/authMiddleware");
const controller = require("../controllers/playerPortalController");
const { submitMyKyc } = require("../controllers/playerKycController");
const { uploadKyc } = require("../middlewares/kycUpload");
router.use(protect, allowRoles("player"));
router.get("/me", controller.getMe);
router.patch("/me", controller.updateMe);
router.get("/tables", controller.getTables);
router.get("/wallet", controller.getWallet);
router.post("/chip-purchase-requests", controller.createPurchaseRequest);
router.get("/kyc", controller.getMyKyc);
router.post("/kyc", uploadKyc.single("document"), submitMyKyc);
router.get("/membership", controller.getMyMembership);
router.get("/sessions", controller.getMySessions);
router.get("/waiting-list", controller.getMyWaitlist);
router.post("/waiting-list", controller.requestWaitlist);
router.patch("/waiting-list/:id/cancel", controller.cancelMyWaitlist);
module.exports = router;
